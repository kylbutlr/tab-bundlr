const { chromium } = require(process.env.PLAYWRIGHT_PACKAGE_PATH || 'playwright');
const fs = require('node:fs/promises');
const assert = require('node:assert/strict');
const path = require('node:path');
const os = require('node:os');
const root = path.resolve(__dirname, '..');
const version = require('../manifest.json').version;
const output = path.join(root, 'dist', `qa-${version}`);
(async () => {
  await fs.mkdir(output, { recursive: true });
  const profile = await fs.mkdtemp(path.join(os.tmpdir(), 'tab-bundlr-qa-'));
  console.log(JSON.stringify({ pid: process.pid, repository: root, command: 'isolated Playwright Chromium extension QA', port: null, profile }));
  let context;
  const deadline = setTimeout(() => { console.error('QA deadline reached'); process.exitCode = 1; void context?.close(); }, 300000);
  const checks = [];
  const errors = [];
  try {
    context = await chromium.launchPersistentContext(profile, { channel: 'chromium', headless: true,
      viewport: { width: 1280, height: 900 }, args: [`--disable-extensions-except=${root}`, `--load-extension=${root}`] });
    await context.route('https://**/*', (route) => route.fulfill({ contentType: 'text/html', body: '<title>QA fixture</title><p>Local fixture</p>' }));
    const worker = context.serviceWorkers()[0] || await context.waitForEvent('serviceworker', { timeout: 15000 });
    const id = worker.url().split('/')[2];
    const page = context.pages()[0] || await context.newPage();
    page.on('pageerror', (error) => errors.push(error.message));
    console.log(JSON.stringify({ reviewTab: page.url(), extensionId: id, browser: context.browser()?.version() }));
    const open = (file) => page.goto(`chrome-extension://${id}/${file}`);
    const message = (payload) => page.evaluate((payload) => chrome.runtime.sendMessage(payload), payload);
    await open('options.html');
    await page.waitForFunction(() => document.querySelector('#form-status').textContent.includes('Manual mode'));
    assert.equal(await page.locator('#enabled').isChecked(), false);
    checks.push('fresh install: no token/account; manual mode');
    await page.locator('#smart-group-name').fill('Documentation');
    await page.locator('#smart-group-pattern').fill('https://docs.example/product');
    await page.locator('#smart-group-form button[type=submit]').click();
    await page.locator('#smart-groups summary').filter({ hasText: 'Documentation' }).waitFor();
    await page.locator('#smart-groups summary').first().click();
    await page.getByRole('button', { name: 'Remove URL', exact: true }).click();
    await page.getByRole('button', { name: 'Undo rule removal' }).waitFor();
    let saved = await page.evaluate(() => chrome.storage.local.get('smartGroups'));
    assert.equal(saved.smartGroups.length, 1);
    assert.equal(saved.smartGroups[0].patterns.length, 0);
    await page.getByRole('button', { name: 'Undo rule removal' }).click();
    saved = await page.evaluate(() => chrome.storage.local.get('smartGroups'));
    assert.equal(saved.smartGroups[0].patterns.length, 1);
    checks.push('workspace creation, last-rule removal preserves workspace, undo restores rule');
    await page.locator('#rule-tester-url').fill('https://docs.example/product/setup');
    await page.locator('#rule-tester-form button').click();
    await page.waitForFunction(() => document.querySelector('#rule-tester-result').textContent.includes('Documentation'));
    checks.push('URL tester renders actual winner');
    // Keyboard-accessible file chooser from the real extension page.
    await page.getByText('Backup and restore', { exact: true }).click();
    await page.locator('#choose-import-settings').focus();
    const chooser = page.waitForEvent('filechooser');
    await page.keyboard.press('Enter');
    await chooser;
    checks.push('keyboard Enter opens settings import chooser');
    await page.screenshot({ path: output + '/settings-desktop.png', fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: output + '/settings-narrow.png', fullPage: true });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    checks.push('settings at desktop and narrow widths without horizontal overflow');
    await page.setViewportSize({ width: 1280, height: 900 });
    // Playwright owns fixture navigation so Chrome has committed URLs before grouping.
    const fixturePages = [];
    for (const suffix of ['setup', 'pinned', 'manual']) {
      const fixture = await context.newPage();
      fixturePages.push(fixture);
      await fixture.goto(`https://docs.example/product/${suffix}`, { waitUntil: 'domcontentloaded' });
    }
    const fixtures = await worker.evaluate(async () => {
      const tabs = await chrome.tabs.query({});
      const matching = tabs.find((tab) => tab.url === 'https://docs.example/product/setup');
      const pinned = tabs.find((tab) => tab.url === 'https://docs.example/product/pinned');
      const manual = tabs.find((tab) => tab.url === 'https://docs.example/product/manual');
      await chrome.tabs.update(pinned.id, { pinned: true });
      const manualGroup = await chrome.tabs.group({ tabIds: [manual.id] });
      await chrome.tabGroups.update(manualGroup, { title: 'Manual QA' });
      return { matching: matching.id, pinned: pinned.id, manual: manual.id, manualGroup };
    });
    const applied = await message({ type: 'FIX_WINDOW' });
    assert.equal(applied.ok, true);
    const tabs = await worker.evaluate(async (ids) => Promise.all(ids.map((id) => chrome.tabs.get(id))), [fixtures.matching, fixtures.pinned, fixtures.manual]);
    console.log(JSON.stringify({ grouping: applied }));
    assert.ok(tabs[0].groupId >= 0);
    assert.equal(tabs[1].groupId, -1);
    assert.equal(tabs[2].groupId, fixtures.manualGroup);
    checks.push('actual Chrome grouping protects pinned tabs and manual groups');
    const undone = await message({ type: 'UNDO_LAST_ACTION' });
    assert.equal(undone.ok, true);
    assert.equal((await worker.evaluate((id) => chrome.tabs.get(id), fixtures.matching)).groupId, -1);
    await message({ type: 'FIX_WINDOW' });
    checks.push('actual Chrome move undo');
    await worker.evaluate((id) => chrome.tabs.update(id, { active: true }), fixtures.matching);
    await open('popup.html');
    await page.locator('#state-pill').filter({ hasText: 'Manual' }).waitFor();
    await page.setViewportSize({ width: 400, height: 900 });
    await page.screenshot({ path: output + '/popup.png', fullPage: true });
    await page.getByRole('button', { name: 'Change workspace rule', exact: true }).click();
    await page.locator('#smart-group-dialog-select').selectOption('__new__');
    await page.locator('#smart-group-dialog-name').fill('New workspace');
    await page.screenshot({ path: output + '/workspace-editor.png', fullPage: true });
    await page.locator('#smart-group-dialog-form button[type=submit]').click();
    await page.waitForFunction(() => !document.querySelector('#smart-group-dialog').open);
    checks.push('unified workspace editor creates a destination and moves a rule');
    await page.getByRole('button', { name: 'Change workspace rule', exact: true }).click();
    await page.locator('#smart-group-dialog-pattern').fill('https://docs.example/product/setup');
    await page.locator('#smart-group-dialog-form button[type=submit]').click();
    await page.waitForFunction(() => !document.querySelector('#smart-group-dialog').open);
    const edited = await page.evaluate(() => chrome.storage.local.get('smartGroups'));
    assert.deepEqual(edited.smartGroups.find((group) => group.name === 'New workspace').patterns, ['https://docs.example/product/setup']);
    checks.push('editing a workspace rule replaces its previous prefix');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.locator('#workspace-search').fill('no-such-workspace');
    await page.getByText('No matching workspaces.', { exact: true }).waitFor();
    await page.locator('#workspace-search').fill('New workspace');
    await page.locator('#groups').getByText('New workspace', { exact: true }).waitFor();
    checks.push('actual extension popup, compact group disclosure, workspace search');
    await open('review.html');
    await page.setViewportSize({ width: 1280, height: 900 });
    await page.locator('#review-summary-title').waitFor();
    // Real duplicate closure: changes after review must be rechecked on confirm.
    const duplicates = [];
    for (let index = 0; index < 3; index += 1) {
      const fixture = await context.newPage();
      await fixture.goto('https://review.example/duplicate', { waitUntil: 'domcontentloaded' });
      duplicates.push(fixture);
    }
    const duplicateIds = await worker.evaluate(async () => (await chrome.tabs.query({})).filter((tab) => tab.url === 'https://review.example/duplicate').map((tab) => tab.id));
    assert.equal(duplicateIds.length, 3);
    await page.evaluate(async () => chrome.tabs.update((await chrome.tabs.getCurrent()).id, { active: true }));
    await page.locator('#refresh-review').click();
    const cluster = page.locator('.duplicate-cluster').filter({ hasText: 'https://review.example/duplicate' });
    const keepers = cluster.getByRole('radio');
    await keepers.first().check();
    const names = await keepers.evaluateAll((inputs) => inputs.map((input) => input.getAttribute('aria-label')));
    assert.equal(new Set(names).size, 3);
    await worker.evaluate((id) => chrome.tabs.update(id, { pinned: true }), duplicateIds[1]);
    await duplicates[2].goto('https://review.example/changed', { waitUntil: 'domcontentloaded' });
    page.once('dialog', (dialog) => dialog.accept());
    await cluster.getByRole('button', { name: 'Close extras' }).click();
    await page.waitForFunction(() => document.querySelector('#review-status').textContent.includes('No tabs closed'));
    assert.equal(await worker.evaluate(async (ids) => (await Promise.all(ids.map((id) => chrome.tabs.get(id)))).length, duplicateIds), 3);
    checks.push('duplicate confirmation rechecks newly pinned and navigated tabs; keepers have distinct accessible names');
    await worker.evaluate((id) => chrome.tabs.update(id, { pinned: false }), duplicateIds[1]);
    await duplicates[2].goto('https://review.example/duplicate', { waitUntil: 'domcontentloaded' });
    await page.locator('#refresh-review').click();
    await keepers.first().check();
    page.once('dialog', (dialog) => dialog.dismiss());
    await cluster.getByRole('button', { name: 'Close extras' }).click();
    assert.equal(await worker.evaluate(async () => (await chrome.tabs.query({})).filter((tab) => tab.url === 'https://review.example/duplicate').length), 3);
    await page.screenshot({ path: output + '/review-populated.png', fullPage: true });
    page.once('dialog', (dialog) => dialog.accept());
    await cluster.getByRole('button', { name: 'Close extras' }).click();
    await page.waitForFunction(() => document.querySelector('#review-status').textContent.startsWith('Closed 2 tabs'));
    assert.equal(await worker.evaluate(async () => (await chrome.tabs.query({})).filter((tab) => tab.url === 'https://review.example/duplicate').length), 1);
    checks.push('duplicate cancel retains all tabs; confirm closes only extras and keeps the selected tab');
    await page.screenshot({ path: output + '/review.png', fullPage: true });
    await open('help.html');
    await page.screenshot({ path: output + '/help.png', fullPage: true });
    await open('runtime-diagnostic.html');
    await page.locator('#refresh').click();
    await page.waitForFunction(() => document.querySelector('#status').textContent.includes('Version ' + chrome.runtime.getManifest().version));
    await page.screenshot({ path: output + '/diagnostic.png', fullPage: true });
    checks.push('review, help and diagnostic surfaces render; diagnostic worker response');
    let deniedSourceRequests = 0;
    await context.route('https://api.source-qa.example/**', (route) => {
      deniedSourceRequests += 1;
      return route.fulfill({ contentType: 'application/json', headers: { 'access-control-allow-origin': '*' }, body: '{"id":"fixture","name":"Fixture"}' });
    });
    const deniedConnection = await worker.evaluate(async (tabId) => {
      const origins = ['https://api.source-qa.example/*'];
      const source = { schemaVersion: 1, id: 'permission-qa', name: 'Permission QA', enabled: true, precedence: 'before-rules', permissionOrigins: origins,
        routes: [{ id: 'item', pagePattern: 'https://docs.example/product/{id}',
          steps: [{ request: { url: 'https://api.source-qa.example/items/{id}' }, extract: { workspaceId: 'id', workspaceName: 'name' } }],
          placement: { workspaceId: '{workspaceId}', workspaceName: '{workspaceName}' } }] };
      await chrome.storage.local.set({ workspaceSources: [source] });
      const granted = await chrome.permissions.contains({ origins });
      return { granted, groupId: (await chrome.tabs.get(tabId)).groupId };
    }, fixtures.matching);
    assert.equal(deniedConnection.granted, false);
    const deniedApply = await message({ type: 'FIX_WINDOW' });
    assert.equal(deniedApply.ok, true);
    assert.equal(deniedApply.failedCount, 0);
    assert.equal((await worker.evaluate((id) => chrome.tabs.get(id), fixtures.matching)).groupId, deniedConnection.groupId);
    assert.equal(deniedSourceRequests, 0);
    await open('options.html');
    await page.getByText('Connections (optional)', { exact: true }).click();
    await page.getByRole('button', { name: 'Review access', exact: true }).waitFor();
    await page.screenshot({ path: output + '/source-access-denied.png', fullPage: true });
    checks.push('actual Chrome host permission denial blocks the connection with zero API requests');
    assert.deepEqual(errors, []);
    await fs.writeFile(output + '/browser-results.json', JSON.stringify({ checks, errors, installedExtension: true, profile: 'disposable', version }, null, 2));
    console.log(JSON.stringify({ checks, errors }));
  } finally {
    clearTimeout(deadline);
    if (context) await context.close();
    await fs.rm(profile, { recursive: true, force: true });
    console.log('CLEANUP: isolated browser closed; disposable profile removed; no server or port used.');
  }
})().catch((error) => { console.error(error.stack); process.exitCode = 1; });
